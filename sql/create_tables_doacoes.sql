DROP TABLE DOACOES CASCADE CONSTRAINTS;
DROP TABLE DOADORES CASCADE CONSTRAINTS;
DROP SEQUENCE DOACOES_ID_DOACAO_SEQ;
CREATE TABLE DOADORES (
CPF VARCHAR2(11) NOT NULL,
NOME VARCHAR2(100) NOT NULL,
EMAIL VARCHAR2(100),
TELEFONE VARCHAR2(15),
CONSTRAINT DOADORES_PK PRIMARY KEY (CPF)
);
CREATE SEQUENCE DOACOES_ID_DOACAO_SEQ START WITH 1 INCREMENT BY 1;
CREATE TABLE DOACOES (
ID_DOACAO NUMBER NOT NULL,
CPF VARCHAR2(11) NOT NULL,
CAMPANHA VARCHAR2(60) NOT NULL,
VALOR NUMBER(10,2) NOT NULL,
DATA_DOACAO DATE NOT NULL,
CONSTRAINT DOACOES_PK PRIMARY KEY (ID_DOACAO),
CONSTRAINT DOACOES_DOADORES_FK FOREIGN KEY (CPF) REFERENCES DOADORES (CPF),
CONSTRAINT DOACOES_VALOR_CK CHECK (VALOR > 0)
);
